// The allow-list of `anariCts check-discrimination`: pairs of Permutation
// values whose Ground truth may score within the Test's own thresholds of each
// other. An entry needs a reason. A pair that renders alike by design belongs
// on a Variant axis instead; a pair whose effect the image can't show is
// opted out with `.noEffectCheck`. Remove an entry once its Test tells the
// two values apart (the check lists such entries).
//
// The entries marked "seeded" are what the check found when it was added
// (2026-11-15), on Ground truth from helide (the Reference device) and from
// halcyon, so that the check could fail CI from the start. They are not
// reasons: each is a Test that can't tell those values apart yet, and ticket 04
// (effect checks for every Permutation) works through them. "identical" means
// the example pair's images were equal on every Channel, which usually means
// the scene can't show the parameter at all.

