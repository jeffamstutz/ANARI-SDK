// halcyon's default preview renderer blends a headlight into every surface
// (eyeLightBlendRatio), so a light's parameter moves the lit pixels by less
// than the thresholds allow. helide implements none of the area lights.
constexpr const char *kHeadlight =
    "the Reference renderer (halcyon's default preview) blends a headlight "
    "into every surface, hiding this light parameter within the Test's "
    "thresholds; the effect check on the Candidate's own render, and "
    "halcyon's quality renderer, show it";
// helide and halcyon don't blend a surface's opacity unless alphaCutoff is
// set (cts-device-findings 04, 05).
constexpr const char *kNoOpacity =
    "the Reference devices (helide, halcyon) don't blend opacity without "
    "alphaCutoff (cts-device-findings 04, 05), so their Ground truth is one "
    "image for every value";
// A parameter that moves the Reference device's image by less than the
// Test's SSIM 0.7 / PSNR 20: washed-out lit colour, or a change on few pixels.
constexpr const char *kWithinThresholds =
    "the values differ in the Reference device's image by less than the "
    "Test's SSIM 0.7 / PSNR 20 (a washed-out lit colour, or a change on few "
    "pixels); the effect check on the Candidate's own render tells them apart";
// A PBR lobe neither helide nor halcyon's preview shades.
constexpr const char *kNoLobe =
    "the Reference devices (helide, halcyon's preview) don't shade with this "
    "PBR parameter, so their Ground truth is one image for every value; the "
    "Candidate's own effect check judges it";
constexpr const char *kNoAmbient =
    "helide reads the renderer's ambientRadiance but never its ambientColor "
    "(even with ignoreAmbientLighting false, which the Test sets where the "
    "renderer lists it), so its Ground truth is one image for every colour";
constexpr const char *kNoFieldFilter =
    "neither helide nor halcyon reads the spatial field's `filter` (always "
    "linear), so their Ground truth is one image for both values";

